"""Run code-server under a supervisor whose lifetime follows the host launcher."""
import ctypes
import fcntl
import json
import os
from pathlib import Path
import signal
import socket
import sqlite3
import subprocess
import sys
import threading
import time

settings = json.loads(sys.stdin.readline())
root = Path('/home/node/.local/share/pi-browser-editor')
root.mkdir(parents=True, exist_ok=True, mode=0o700)
lock = (root / 'editor.lock').open('a+')
try:
    fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
except BlockingIOError:
    raise SystemExit('A browser editor is still running in this container. Stop and restart the sandbox before retrying.')
# Do not keep a desktop remote connection alongside the browser-only editor.
for item in Path('/proc').glob('[0-9]*/cmdline'):
    if item.parent.name == str(os.getpid()):
        continue
    try:
        args = item.read_bytes().split(b'\0')
    except (OSError, PermissionError):
        continue
    if any(b'/.vscode-server/' in arg or b'/.vscode-server-insiders/' in arg for arg in args):
        raise SystemExit('A desktop VS Code server is running. Use a fresh sandbox for the browser editor.')

extensions = root / 'extensions'
extensions.mkdir(exist_ok=True)
for target in extensions.iterdir():
    if target.is_symlink() and str(target.readlink()).startswith('/opt/pendant/') and not target.exists():
        target.unlink()
for source in Path('/opt/pendant').iterdir():
    target = extensions / source.name
    if not target.exists():
        target.symlink_to(source, target_is_directory=True)
# Read the machine settings already generated by bootstrap, including model/proxy settings.
machine = Path('/home/node/.vscode-server/data/Machine/settings.json')
values = json.loads(machine.read_text()) if machine.exists() else {}
values.update({'extensions.autoUpdate': False, 'extensions.autoCheckUpdates': False,
               'workbench.startupEditor': 'none', 'telemetry.telemetryLevel': 'off',
               'remote.autoForwardPorts': False, 'chat.disableAIFeatures': True})
user = root / 'data/User'
user.mkdir(parents=True, exist_ok=True)
user_settings = user / 'settings.json'
existing = json.loads(user_settings.read_text()) if user_settings.exists() else {}
existing.update(values)
existing.setdefault('workbench.colorTheme', 'Default Dark Modern')
existing.setdefault('workbench.secondarySideBar.defaultVisibility', 'visible')
user_settings.write_text(json.dumps(existing))
# Seed native view storage once, preserving subsequent layout choices.
storage = user / 'globalStorage/state.vscdb'
storage.parent.mkdir(exist_ok=True)
with sqlite3.connect(storage) as database:
    database.execute('CREATE TABLE IF NOT EXISTS ItemTable (key TEXT UNIQUE ON CONFLICT REPLACE, value BLOB)')
    database.execute('INSERT OR IGNORE INTO ItemTable (key, value) VALUES (?, ?)',
                     ('views.customizations', json.dumps({
                         'viewContainerLocations': {'workbench.view.extension.pendant-container': 2},
                         'viewLocations': {}, 'viewContainerBadgeEnablementStates': {},
                     })))
# The selected workspace is trusted; other container folders keep normal trust checks.
trust_store = Path('/home/node/.vscode-oss-shared/sharedStorage/state.vscdb')
trust_store.parent.mkdir(parents=True, exist_ok=True)
with sqlite3.connect(trust_store) as database:
    database.execute('CREATE TABLE IF NOT EXISTS ItemTable (key TEXT UNIQUE ON CONFLICT REPLACE, value BLOB)')
    key = 'content.trust.model.key'
    row = database.execute('SELECT value FROM ItemTable WHERE key = ?', (key,)).fetchone()
    trust = json.loads(row[0]) if row else {'uriTrustInfo': []}
    uri = {'scheme': 'vscode-remote', 'authority': settings['authority'], 'path': '/workspace'}
    entries = trust['uriTrustInfo']
    if not any(all(entry['uri'].get(k) == v for k, v in uri.items()) and entry.get('trusted') for entry in entries):
        entries.append({'uri': uri, 'trusted': True})
    database.execute('INSERT OR REPLACE INTO ItemTable (key, value) VALUES (?, ?)', (key, json.dumps(trust)))

config = root / 'config.yaml'
config.write_text(json.dumps({'hashed-password': settings['password_hash']}) + '\n')
config.chmod(0o600)
sock = root / 'editor.sock'
sock.unlink(missing_ok=True)
env = dict(os.environ)
for key in ('PASSWORD', 'HASHED_PASSWORD', 'GITHUB_TOKEN', 'VSCODE_IPC_HOOK_CLI'):
    env.pop(key, None)
command = [settings['binary'], '--config', str(config), '--socket', str(sock),
           '--socket-mode', '600', '--auth', 'password', '--user-data-dir', str(root / 'data'),
           '--extensions-dir', str(extensions), '--disable-telemetry', '--disable-update-check',
           '--disable-proxy', '--disable-file-downloads', '--disable-file-uploads',
           '--disable-file-cache', '--enable-remote-storage', settings['cwd']]

# Adopt editor descendants, including terminal shells that create separate sessions.
# This allows shutdown without killing unrelated Pi CLI processes in this sandbox.
if ctypes.CDLL(None, use_errno=True).prctl(36, 1, 0, 0, 0) != 0:
    raise RuntimeError('Could not supervise browser editor descendants')
process = subprocess.Popen(command, env=env, stdout=sys.stderr, start_new_session=True, pass_fds=(lock.fileno(),))
stopping = threading.Event()

def stop(*_):
    stopping.set()

def descendants():
    parents = {}
    for item in Path('/proc').glob('[0-9]*/status'):
        try:
            parent = next(line.split()[1] for line in item.read_text().splitlines() if line.startswith('PPid:'))
            parents[int(item.parent.name)] = int(parent)
        except (OSError, StopIteration, ValueError):
            continue
    owned = {os.getpid()}
    while added := {pid for pid, parent in parents.items() if parent in owned} - owned:
        owned.update(added)
    return owned - {os.getpid()}

def disconnected():
    sys.stdin.read()
    stop()

threading.Thread(target=disconnected, daemon=True).start()
for signum in (signal.SIGINT, signal.SIGTERM, signal.SIGHUP):
    signal.signal(signum, stop)
try:
    deadline = time.monotonic() + 55
    while not stopping.is_set() and process.poll() is None:
        try:
            with socket.socket(socket.AF_UNIX) as connection:
                connection.connect(str(sock))
            print('ready', flush=True)
            break
        except OSError:
            if time.monotonic() > deadline:
                raise RuntimeError('Browser editor did not open its socket')
            stopping.wait(0.1)
    while not stopping.wait(0.2) and process.poll() is None:
        pass
finally:
    for signum, delay in ((signal.SIGTERM, 3), (signal.SIGKILL, 2)):
        deadline = time.monotonic() + delay
        while children := descendants():
            for pid in children:
                try:
                    os.kill(pid, signum)
                except ProcessLookupError:
                    pass
            process.poll()
            try:
                while os.waitpid(-1, os.WNOHANG)[0]:
                    pass
            except ChildProcessError:
                pass
            if time.monotonic() >= deadline:
                break
            time.sleep(0.1)
    sock.unlink(missing_ok=True)
